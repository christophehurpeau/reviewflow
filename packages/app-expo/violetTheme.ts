import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { AccentName, PaletteSpec } from "alouette/theme-generator";
import { generateTheme } from "alouette/theme-generator";

/** The merged pull request's violet, as on GitHub: done, nothing left to do. */
export const violetPaletteSpec: PaletteSpec = {
  type: "accent",
  hue: 295,
  hueHi: 300,
};

/*
  `violet` is an accent alouette does not have: its set is closed, and only the
  existing accents can be re-colored. At runtime an accent is nothing but the
  `<mode>_<accent>` theme name — a class on web, a `themeVariables` key on
  native — so the violet themes are the `info` ones of the app's palette
  re-colored violet, renamed. Same OKLCH ramp, same token set, nothing
  hand-picked.
*/
const sourceAccent = "info";

const generatedHeader = "/* Generated by build-theme.ts. DO NOT EDIT. */";

const blockPattern = (selector: string): RegExp =>
  new RegExp(String.raw`^ *\.${selector} \{\n[^}]*\}`, "gm");

const renameBlock = (block: string): string =>
  block.replace(`_${sourceAccent} {`, "_violet {");

/*
  alouette 25 resolves `system` in CSS: a `system_<accent>` scope is what an
  accent under the default color mode asks for, so violet needs the
  `.system_violet` pair too — light tokens, then the dark ones under
  `prefers-color-scheme`, the same shape alouette emits for its own accents.
  Without it a violet badge renders in the surrounding accent until the user
  picks an explicit mode.
*/
const extractVioletBlocks = (css: string): string => {
  const explicit = ["light", "dark"].map((mode) => {
    const block = new RegExp(
      String.raw`^ *\.${mode}_${sourceAccent} \{\n[^}]*\}`,
      "m",
    ).exec(css)?.[0];
    if (!block) {
      throw new Error(
        `alouette no longer emits .${mode}_${sourceAccent} as expected`,
      );
    }
    return renameBlock(block);
  });
  const [systemLight, systemDark] = [
    ...css.matchAll(blockPattern(`system_${sourceAccent}`)),
  ].map((match) => match[0]);
  if (!systemLight || !systemDark) {
    throw new Error(
      `alouette no longer emits .system_${sourceAccent} as expected`,
    );
  }
  return [
    ...explicit,
    renameBlock(systemLight),
    `    @media (prefers-color-scheme: dark) {\n${renameBlock(systemDark)}\n    }`,
  ].join("\n\n");
};

const serializeVariables = (variables: Record<string, string>): string =>
  Object.entries(variables)
    .map(([name, value]) => `    "${name}": "${value}",`)
    .join("\n");

export interface WriteVioletThemeParams {
  outDir: string;
  /** the overrides passed to alouette's `writeTheme`, so violet shares its grays */
  palette: Partial<Record<AccentName, PaletteSpec>>;
}

/**
 * Writes `palette-violet.css` and `violetThemeVariables.ts` into `outDir`,
 * beside the alouette palette: the themes `mergedAccent` names. `global.css`
 * imports the CSS after the palette, and the root layout spreads the variables
 * into the map it passes to `AlouetteProvider`.
 */
export const writeVioletTheme = ({
  outDir,
  palette,
}: WriteVioletThemeParams): void => {
  const violetTheme = generateTheme({
    ...palette,
    [sourceAccent]: violetPaletteSpec,
  });
  mkdirSync(outDir, { recursive: true });

  writeFileSync(
    join(outDir, "palette-violet.css"),
    `${generatedHeader}
/* The violet accent themes, imported after the palette they extend. */
@layer theme {
  @supports (display: contents) {
${extractVioletBlocks(violetTheme.css)}
  }
}

@supports (color: oklch(0 0 0)) {
  @layer theme {
${extractVioletBlocks(violetTheme.oklchCss)}
  }
}
`,
  );

  writeFileSync(
    join(outDir, "violetThemeVariables.ts"),
    `${generatedHeader}

/** Native half of \`palette-violet.css\`, merged into the alouette map. */
export const violetThemeVariables = {
  light_violet: {
${serializeVariables(violetTheme.themeVariables[`light_${sourceAccent}`])}
  },
  dark_violet: {
${serializeVariables(violetTheme.themeVariables[`dark_${sourceAccent}`])}
  },
};
`,
  );
};
